// Applies brand/brand.json to the places that need the app's name and identity:
//   frontend/src-tauri/tauri.conf.json         productName, mainBinaryName, identifier, window title
//   frontend/src/lib/brand.generated.ts        constants for the interface
//   frontend/src-tauri/src/brand_generated.rs  constants for the Rust core
// Usage: node scripts/brand-apply.mjs [--check]     (--check fails if anything has drifted)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { isMain, repoRoot } from './lint/lib.mjs';

const EM = String.fromCharCode(0x2014);
const TEXT = new RegExp('^[^"\\\\\\u0000-\\u001f' + EM + ']{1,200}$');
const SLUG = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const BUNDLE_ID = /^[a-z][a-z0-9]*(\.[a-z][a-z0-9-]*){2,}$/;
const DIR_NAME = new RegExp('^[^<>:"/\\\\|?*\\u0000-\\u001f' + EM + ']{1,80}$');

const FILES = {
  brand: 'brand/brand.json',
  conf: 'frontend/src-tauri/tauri.conf.json',
  ts: 'frontend/src/lib/brand.generated.ts',
  rs: 'frontend/src-tauri/src/brand_generated.rs',
};

/** Returns a list of problems (empty when the brand is usable). */
export function validateBrand(b) {
  const problems = [];
  const text = (key, value, re = TEXT) => {
    if (typeof value !== 'string' || !re.test(value)) problems.push(`${key}: missing or contains a quote, backslash, control character or em dash`);
  };
  if (!b || typeof b !== 'object') return ['brand: not an object'];
  text('name', b.name);
  if (typeof b.slug !== 'string' || !SLUG.test(b.slug)) problems.push('slug: use lowercase letters, digits and single hyphens');
  if (typeof b.bundleId !== 'string' || !BUNDLE_ID.test(b.bundleId)) problems.push('bundleId: use a lowercase reverse domain name such as com.example.app');
  text('windowTitle', b.windowTitle);
  text('tagline', b.tagline);
  text('vaultDirName', b.vaultDirName, DIR_NAME);
  text('upstreamCredit', b.upstreamCredit);
  const l = b.legacy;
  if (!l || typeof l !== 'object') {
    problems.push('legacy: block is required (old identifier and folder names the app must still recognise)');
  } else {
    if (typeof l.identifier !== 'string' || !BUNDLE_ID.test(l.identifier)) problems.push('legacy.identifier: not a reverse domain name');
    text('legacy.name', l.name);
    for (const key of ['templatesDir', 'configDir', 'recordingsDirName']) text(`legacy.${key}`, l[key], DIR_NAME);
    text('legacy.tempPrefix', l.tempPrefix);
  }
  return problems;
}

function replaceFirst(text, re, build, what) {
  if (!re.test(text)) throw new Error(`tauri.conf.json: could not find ${what}`);
  return text.replace(re, (_m, head) => build(head));
}

/** Edits only the identity keys, so the rest of the file keeps its formatting. */
export function applyToTauriConf(text, b) {
  let out = replaceFirst(text, /("productName"\s*:\s*)"[^"]*"/, (h) => `${h}${JSON.stringify(b.name)}`, 'productName');
  if (/"mainBinaryName"\s*:/.test(out)) {
    out = replaceFirst(out, /("mainBinaryName"\s*:\s*)"[^"]*"/, (h) => `${h}${JSON.stringify(b.slug)}`, 'mainBinaryName');
  } else {
    out = out.replace(/^([ \t]*)("productName"\s*:\s*"[^"]*",?)[ \t]*$/m, (_m, indent, line) => `${indent}${line}\n${indent}"mainBinaryName": ${JSON.stringify(b.slug)},`);
  }
  out = replaceFirst(out, /("identifier"\s*:\s*)"[^"]*"/, (h) => `${h}${JSON.stringify(b.bundleId)}`, 'identifier');
  out = replaceFirst(out, /("windows"\s*:\s*\[\s*\{[^{}]*?"title"\s*:\s*)"[^"]*"/s, (h) => `${h}${JSON.stringify(b.windowTitle)}`, 'the main window title');
  JSON.parse(out); // throws if an edit broke the file
  return out;
}

const HEADER = 'GENERATED by frontend/scripts/brand-apply.mjs from brand/brand.json. Do not edit by hand.';

export function renderTs(b) {
  return `// ${HEADER}
export const BRAND = {
  name: ${JSON.stringify(b.name)},
  slug: ${JSON.stringify(b.slug)},
  bundleId: ${JSON.stringify(b.bundleId)},
  windowTitle: ${JSON.stringify(b.windowTitle)},
  tagline: ${JSON.stringify(b.tagline)},
  vaultDirName: ${JSON.stringify(b.vaultDirName)},
  upstreamCredit: ${JSON.stringify(b.upstreamCredit)},
} as const;
`;
}

export function renderRs(b) {
  const c = (name, value) => `pub const ${name}: &str = ${JSON.stringify(value)};`;
  return `// ${HEADER}

${c('NAME', b.name)}
${c('SLUG', b.slug)}
${c('BUNDLE_ID', b.bundleId)}
${c('WINDOW_TITLE', b.windowTitle)}
${c('TAGLINE', b.tagline)}
${c('VAULT_DIR_NAME', b.vaultDirName)}
${c('UPSTREAM_CREDIT', b.upstreamCredit)}

// Names from the earlier product that the app must still recognise (data adoption, cleanup).
${c('LEGACY_NAME', b.legacy.name)}
${c('LEGACY_IDENTIFIER', b.legacy.identifier)}
${c('LEGACY_TEMPLATES_DIR', b.legacy.templatesDir)}
${c('LEGACY_CONFIG_DIR', b.legacy.configDir)}
${c('LEGACY_RECORDINGS_DIR_NAME', b.legacy.recordingsDirName)}
${c('LEGACY_TEMP_PREFIX', b.legacy.tempPrefix)}
`;
}

function load(root) {
  const brand = JSON.parse(readFileSync(path.join(root, FILES.brand), 'utf8'));
  const problems = validateBrand(brand);
  if (problems.length) throw new Error('brand/brand.json is not valid:\n  ' + problems.join('\n  '));
  return brand;
}

function expected(root) {
  const brand = load(root);
  const confPath = path.join(root, FILES.conf);
  return [
    { file: FILES.conf, content: applyToTauriConf(readFileSync(confPath, 'utf8'), brand) },
    { file: FILES.ts, content: renderTs(brand) },
    { file: FILES.rs, content: renderRs(brand) },
  ];
}

/** Files that differ from what brand.json says they should contain. */
export function checkAll(root) {
  return expected(root)
    .filter(({ file, content }) => !existsSync(path.join(root, file)) || readFileSync(path.join(root, file), 'utf8') !== content)
    .map(({ file }) => file);
}

/** Writes every file that is missing or different. Returns the files written. */
export function applyAll(root) {
  const written = [];
  for (const { file, content } of expected(root)) {
    const full = path.join(root, file);
    if (existsSync(full) && readFileSync(full, 'utf8') === content) continue;
    mkdirSync(path.dirname(full), { recursive: true });
    writeFileSync(full, content);
    written.push(file);
  }
  return written;
}

function main() {
  const root = repoRoot();
  if (process.argv.includes('--check')) {
    const drift = checkAll(root);
    if (drift.length) {
      console.error('brand: FAILED, these files do not match brand/brand.json (run `pnpm brand:apply`):');
      for (const f of drift) console.error('  ' + f);
      process.exit(1);
    }
    console.log('brand: ok (generated files match brand/brand.json)');
    return;
  }
  const written = applyAll(root);
  console.log(written.length ? `brand: updated ${written.join(', ')}` : 'brand: already up to date');
}

if (isMain(import.meta.url)) main();
